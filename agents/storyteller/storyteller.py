def _collect_citation_scan_text(mode_b: dict) -> str:
    """
    Build the text corpus that the citation L1 check scans. Excludes:
      - top-level administrative / meta-commentary fields (CITATION_SCAN_EXCLUDED_FIELDS)
      - sub-paths within recommended_action that are technical/operational layers
        (technical_annex, implementation_path, timeline, secondary)
    The remaining text — executive_narrative, technical_deep_dive, recommended_action.primary,
    financial_projection, known_limitations, statistical_verdict, scale_impact_declaration —
    is the stakeholder-facing prose that must carry [^N] markers.
    """
    if not isinstance(mode_b, dict):
        return ""
    pieces = []
    for k, v in mode_b.items():
        if k in CITATION_SCAN_EXCLUDED_FIELDS:
            continue
        if isinstance(v, dict):
            # Strip excluded subpaths
            filtered = {sk: sv for sk, sv in v.items() if (k, sk) not in CITATION_SCAN_EXCLUDED_SUBPATHS}
            pieces.extend(_collect_prose_strings(filtered))
        else:
            pieces.extend(_collect_prose_strings(v))
    return "\n\n".join(pieces)


def _l1_check_causal_language(text: str) -> dict:
    """
    L1 Veto 1: Detect causal language without causal evidence.

    Statistical methodology context is exempt: a causal verb inside a sentence
    describing an analytical limitation (e.g. "underpowered due to small sample
    size") is not a data-causal claim and does not trigger the veto.

    Returns: {"passed": bool, "violations_found": [str], "check_description": str}
    """
    violations = []
    text_lower = text.lower()

    for phrase in CAUSAL_VERBS:
        # Use word-boundary regex to avoid substring false positives
        # (e.g., "forced" matching "enforced", "led to" matching "controlled to").
        pattern = re.compile(r'\b' + re.escape(phrase) + r'\b')
        search_start = 0
        while True:
            m = pattern.search(text_lower, search_start)
            if not m:
                break
            idx = m.start()

            # Extract the sentence containing this match.
            # Look backward for the most recent sentence-ending boundary, skipping
            # decimal-point periods (e.g., 0.72, 1.52, p<0.001) which are not
            # sentence terminators.
            pre = text_lower[:idx]

            def _last_sentence_break(s: str) -> int:
                """Return last index of a real sentence boundary (skip decimal points)."""
                best = -1
                for i in range(len(s) - 1, -1, -1):
                    ch = s[i]
                    if ch == '\n' or ch == '!' or ch == '?':
                        return i
                    if ch == '.':
                        # Skip if surrounded by digits (decimal point) or preceded by digit
                        prev_is_digit = i > 0 and s[i-1].isdigit()
                        next_is_digit = i + 1 < len(s) and s[i+1].isdigit()
                        if prev_is_digit and next_is_digit:
                            continue  # decimal like 0.72
                        return i
                return -1

            last_end = _last_sentence_break(pre)
            sent_start = last_end + 1 if last_end >= 0 else 0

            # Look forward for the next sentence-ending boundary, also skipping decimals.
            post = text_lower[idx:]
            next_end = -1
            for i in range(len(post)):
                ch = post[i]
                if ch == '\n' or ch == '!' or ch == '?':
                    next_end = i
                    break
                if ch == '.':
                    prev_is_digit = i > 0 and post[i-1].isdigit()
                    next_is_digit = i + 1 < len(post) and post[i+1].isdigit()
                    if prev_is_digit and next_is_digit:
                        continue
                    next_end = i
                    break
            sent_end = idx + next_end + 1 if next_end >= 0 else len(text_lower)

            sentence = text_lower[sent_start:sent_end]

            # Exempt if the sentence describes statistical methodology.
            is_stats_context = any(kw in sentence for kw in STATISTICAL_METHODOLOGY_KEYWORDS)

            if not is_stats_context:
                context = text[max(0, idx - 30):idx + 50]
                violations.append(f"'{phrase}' found in: '...{context}...'")

            search_start = idx + len(phrase)

    return {
        "passed": len(violations) == 0,
        "violations_found": violations,
        "check_description": (
            "No causal language permitted without causal evidence (L1 Veto 1). "
            "Statistical methodology context (e.g. 'underpowered due to small sample size') is exempt."
        ),
    }


