def _collect_prose_strings(obj: object, min_length: int = 40) -> list:
    """
    Recursively collect all string values from a parsed JSON object that are
    likely to be prose text (length >= min_length). Used to build a clean text
    corpus for L1 veto scanning — avoids JSON structural artifacts and decimal-
    point fragmentation that occurs when scanning json.dumps() output.
    """
    texts = []
    if isinstance(obj, dict):
        for v in obj.values():
            texts.extend(_collect_prose_strings(v, min_length))
    elif isinstance(obj, list):
        for item in obj:
            texts.extend(_collect_prose_strings(item, min_length))
    elif isinstance(obj, str) and len(obj) >= min_length:
        texts.append(obj)
    return texts


