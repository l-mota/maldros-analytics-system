def _l1_check_citation_coverage(text: str, mode_b_section: dict) -> dict:
    """
    L1 Veto 2 (C-020): Verify factual claims carry a [^N] footnote marker,
    AND verify every [^N] used has a matching footnote entry with a valid source.

    For each factual pattern match (number, %, $, etc.):
      - Check whether a [^N] marker appears within a ±300 char window.
    String-level fallback retained: a prose string that contains at least one
    [^N] marker is treated as cited even if some claims fall outside the window.

    Then validate the footnotes asset:
      - Every [^N] marker used inline must appear as a footnote entry.
      - Every footnote entry must have a recognized "source" value.

    Phase 1 threshold: 80% of factual claims cited; Phase 2 raises to 100%.
    """
    factual_patterns = [
        r'\d+\.?\d*%',           # percentages: 10%, 10.5%
        r'\$[\d,\.]+[MKB]?\b',   # dollar amounts: $5.89M, $1,000
        r'\d+\.\d+',             # decimal numbers: 16.54, 0.001
        r'\b\d+x\b',             # rate ratios: 16x, 2x
        r'\b\d+×',               # rate ratios with ×
        r'\b\d{2,} accounts?\b', # account counts: 41 accounts
        r'\b\d{2,} incidents?\b', # incident counts
        r'\brate ratio of\b',    # specific rate ratio claim
        r'\bgini coefficient\b', # Gini coefficient with result
        r'p\s*[<=]\s*0\.',       # specific p-value result
    ]

    # Strip footnote markers themselves so [^1] doesn't accidentally match \d+ patterns.
    # We track positions in the original text but exclude pattern hits inside marker text.
    marker_re = re.compile(r'\[\^(\d+)\]')
    marker_spans = [(m.start(), m.end(), int(m.group(1))) for m in marker_re.finditer(text)]
    inline_markers_used = {n for _, _, n in marker_spans}

    def _inside_marker(pos: int) -> bool:
        return any(s <= pos < e for s, e, _ in marker_spans)

    # Collect factual positions (excluding those inside markers themselves)
    all_positions = []
    for pattern in factual_patterns:
        for m in re.finditer(pattern, text, re.I):
            if not _inside_marker(m.start()):
                all_positions.append(m.start())

    # Deduplicate: merge matches within 30 chars
    all_positions.sort()
    deduped = []
    last_pos = -100
    for pos in all_positions:
        if pos - last_pos > 30:
            deduped.append(pos)
            last_pos = pos

    # Prose-string boundaries for the string-level fallback
    prose_string_boundaries = []
    search_start = 0
    for chunk in text.split("\n\n"):
        idx = text.find(chunk, search_start)
        if idx >= 0:
            prose_string_boundaries.append((idx, idx + len(chunk), chunk))
            search_start = idx + len(chunk)

    def _prose_string_for_pos(pos: int) -> str:
        for start, end, chunk in prose_string_boundaries:
            if start <= pos < end:
                return chunk
        return ""

    # For each factual position, look for a [^N] marker within ±300 chars; fall back to
    # string-level coverage if the proximity window misses.
    cited_count = 0
    uncited_samples = []
    for pos in deduped:
        window_start = max(0, pos - 80)
        window_end = min(len(text), pos + 300)
        window = text[window_start:window_end]
        has_marker = bool(marker_re.search(window))
        if not has_marker:
            containing_string = _prose_string_for_pos(pos)
            if containing_string and marker_re.search(containing_string):
                has_marker = True
        if has_marker:
            cited_count += 1
        else:
            sample = text[max(0, pos - 20):min(len(text), pos + 80)]
            uncited_samples.append(sample)

    total = len(deduped)
    coverage_pct = round(cited_count / total * 100, 1) if total > 0 else 100.0
    coverage_passed = coverage_pct >= 80.0  # Phase 1 threshold

    # Footnote integrity: every [^N] used must have a matching footnote entry
    # with a valid "source" value.
    footnotes = mode_b_section.get("footnotes", []) if isinstance(mode_b_section, dict) else []
    if not isinstance(footnotes, list):
        footnotes = []
    footnote_ns = set()
    footnote_violations = []
    for fn in footnotes:
        if not isinstance(fn, dict):
            footnote_violations.append(f"Footnote entry is not an object: {fn}")
            continue
        n = fn.get("n")
        source = (fn.get("source") or "").strip()
        if not isinstance(n, int):
            footnote_violations.append(f"Footnote has non-integer 'n': {fn}")
            continue
        footnote_ns.add(n)
        if source not in VALID_FOOTNOTE_SOURCES:
            footnote_violations.append(
                f"Footnote [^{n}] uses unrecognized source '{source}'. "
                f"Valid: {sorted(VALID_FOOTNOTE_SOURCES)}"
            )

    orphan_inline = sorted(inline_markers_used - footnote_ns)
    if orphan_inline:
        footnote_violations.append(
            f"Inline marker(s) {[f'[^{n}]' for n in orphan_inline]} have no matching footnote entry."
        )

    # Inline [source: ...] text in the executive layer is forbidden under C-020 rule (d).
    inline_source_text = re.findall(r'\[source:[^\]]*\]', text, re.I)
    if inline_source_text:
        footnote_violations.append(
            f"Inline [source: ...] text is forbidden (C-020 rule d). Use [^N] markers and the "
            f"footnotes asset instead. Found {len(inline_source_text)} occurrence(s): "
            f"{inline_source_text[:3]}"
        )

    integrity_passed = len(footnote_violations) == 0
    passed = coverage_passed and integrity_passed

    return {
        "passed": passed,
        "coverage_pct": coverage_pct,
        "coverage_passed": coverage_passed,
        "integrity_passed": integrity_passed,
        "uncited_claims": [s[:120] for s in uncited_samples[:5]],
        "footnote_violations": footnote_violations,
        "total_factual_sentences": total,   # field name kept for schema compat
        "cited_count": cited_count,
        "inline_markers_used": sorted(inline_markers_used),
        "footnote_numbers_present": sorted(footnote_ns),
        "check_description": (
            "Factual claims require [^N] marker (C-020). Every marker must reference an entry "
            "in the footnotes asset with a recognized source. Inline [source: ...] text is forbidden."
        ),
    }


def _l1_check_omission_audit(output_text: str, evidence_content: dict, stat_content: dict) -> dict:
    """
    L1 Veto 3: Verify all material findings from upstream artifacts appear in output.
    Material findings are: primary_conclusion, statistical_verdict, and top cluster finding.
    """
    material_findings = []

    # Must mention: primary conclusion
    conclusion = evidence_content.get("primary_conclusion", "")
    if conclusion:
        material_findings.append(("primary_conclusion", conclusion.lower().replace("_", " ")))

    # Must mention: statistical verdict
    stat_verdict = stat_content.get("statistical_verdict", "")
    if stat_verdict:
        material_findings.append(("statistical_verdict", stat_verdict.lower().replace("_", " ")))

    # Must mention: cluster finding (if coordinated abuse was found)
    ga = evidence_content.get("analysis_results", {}).get("graph_analysis", {})
    n_clustered = ga.get("n_clustered_accounts_3plus", 0)
    if n_clustered > 0:
        material_findings.append(("cluster_finding", f"cluster"))

    # Must mention: financial impact
    fi = evidence_content.get("analysis_results", {}).get("financial_impact_table", {})
    fi_total = fi.get("q1_api_abuse_total", 0)
    if fi_total > 0:
        material_findings.append(("financial_impact", "financial"))

    output_lower = output_text.lower()
    omitted = []
    for name, keyword in material_findings:
        # Accept both space-separated and underscore-separated forms
        # e.g. "conditionally validated" and "conditionally_validated" are both valid
        keyword_underscored = keyword.replace(" ", "_")
        if keyword not in output_lower and keyword_underscored not in output_lower:
            omitted.append(f"{name}: expected reference to '{keyword}'")

    return {
        "passed": len(omitted) == 0,
        "omitted_material_findings": omitted,
        "audit_description": f"Checked {len(material_findings)} material findings; {len(omitted)} missing",
    }


